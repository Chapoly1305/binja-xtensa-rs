//! The [`Opcode`] enum: one variant per distinct mnemonic the reference
//! Python decoder can produce (317 in total).

macro_rules! opcodes {
    ($($variant:ident = $mnem:literal,)*) => {
        /// One variant per distinct mnemonic string of the reference decoder.
        ///
        /// The 64 MAC16 arithmetic forms (`UMUL/MUL/MULA/MULS` x `AA/AD/DA/DD`
        /// x `LL/HL/LH/HH`) and the 16 MAC16 compound load forms
        /// (`MULA.{DA,DD}.{half}.{LDINC,LDDEC}`) are contiguous blocks at the
        /// end; use [`crate::Insn::mac_kind`] and friends instead of relying on
        /// the discriminants.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
        #[repr(u16)]
        pub enum Opcode {
            $(
                #[doc = concat!("`", $mnem, "`")]
                $variant,
            )*
        }

        impl Opcode {
            /// Every opcode, in discriminant order.
            pub const ALL: &'static [Opcode] = &[$(Opcode::$variant,)*];

            /// The exact mnemonic string of the reference decoder
            /// (e.g. `"ADD.N"`, `"MULA.DD.LL.LDINC"`).
            pub const fn mnemonic(self) -> &'static str {
                match self {
                    $(Opcode::$variant => $mnem,)*
                }
            }
        }
    };
}

