#!/usr/bin/env python3
"""Generate crates/binja-xtensa/src/model.rs from golden/arch_model_v1.json.

The JSON is dumped from the reference plugin by ``arch_model.py``; generating
the native tables from it keeps register order, sizes, the register stack,
intrinsic signatures and the calling convention identical by construction.
Re-run after updating the JSON; CI checks that the committed file is current.
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
model = json.loads((root / "golden/arch_model_v1.json").read_text())
regs = model["regs"]
assert [r["index"] for r in regs] == list(range(len(regs))), "register ids must be dense"
for r in regs:
    assert r["full_width"] == r["name"] and r["offset"] == 0 and r["extend"] == "NoExtend", r
index = {r["name"]: r["index"] for r in regs}

stacks = model["reg_stacks"]
assert list(stacks) == ["physical_ar"]
st = stacks["physical_ar"]
storage = [index[n] for n in st["storage"]]
assert storage == list(range(storage[0], storage[0] + len(storage))), "stack storage must be contiguous"
assert not st["top_relative"]

TYPES = {"uint32_t": "U32"}
out = []
w = out.append
w("// @generated by harness/gen_model_rs.py from golden/arch_model_v1.json. Do not edit.")
w("")
w("/// Register names and sizes, indexed by register id.")
w(f"pub const REGISTERS: [(&str, u8); {len(regs)}] = [")
for r in regs:
    w(f'    ("{r["name"]}", {r["size"]}),')
w("];")
w("")
for name in ("stack_pointer", "link_reg"):
    w(f"pub const {name.upper()}: u32 = {index[model[name]]}; // {model[name]}")
w(f'pub const REG_STACK_NAME: &str = "physical_ar";')
w(f"pub const REG_STACK_STORAGE_FIRST: u32 = {storage[0]};")
w(f"pub const REG_STACK_STORAGE_COUNT: usize = {len(storage)};")
w(f"pub const REG_STACK_TOP: u32 = {index[st['stack_top']]}; // {st['stack_top']}")
w("")
w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
w("pub enum ScalarType {")
w("    U32,")
w("}")
w("")
w("pub struct IntrinsicDef {")
w("    pub name: &'static str,")
w("    pub inputs: &'static [(&'static str, ScalarType)],")
w("    pub outputs: &'static [ScalarType],")
w("}")
w("")
order = model["intrinsic_order"]
w("/// Intrinsics, indexed by intrinsic id.")
w(f"pub const INTRINSICS: [IntrinsicDef; {len(order)}] = [")
for n in order:
    d = model["intrinsics"][n]
    ins = ", ".join(f'("{nm}", ScalarType::{TYPES[t]})' for t, nm in d["inputs"])
    outs = ", ".join(f"ScalarType::{TYPES[t]}" for t in d["outputs"])
    w(f'    IntrinsicDef {{ name: "{n}", inputs: &[{ins}], outputs: &[{outs}] }},')
w("];")
w("")
ccs = model["calling_conventions"]
assert list(ccs) == ["default"] and model["default_calling_convention"] == "default"
cc = ccs["default"]
assert not cc["callee_saved_regs"] and not cc["float_arg_regs"] and cc["float_return_reg"] is None
assert cc["global_pointer_reg"] is None


def names(key):
    return "&[" + ", ".join(f'"{n}"' for n in cc[key]) + "]"


w("pub mod cc {")
w('    pub const NAME: &str = "default";')
for key in ("caller_saved_regs", "int_arg_regs", "implicitly_defined_regs"):
    w(f"    pub const {key.upper()}: &[&str] = {names(key)};")
w(f'    pub const INT_RETURN_REG: &str = "{cc["int_return_reg"]}";')
w(f'    pub const HIGH_INT_RETURN_REG: &str = "{cc["high_int_return_reg"]}";')
for key in ("arg_regs_share_index", "arg_regs_for_varargs", "stack_reserved_for_arg_regs",
            "stack_adjusted_on_return", "eligible_for_heuristics"):
    w(f"    pub const {key.upper()}: bool = {str(cc[key]).lower()};")
w("}")
w("")
for key in ("address_size", "default_int_size", "max_instr_length", "instr_alignment"):
    w(f"pub const {key.upper()}: usize = {model[key]};")

text = "\n".join(out) + "\n"
dest = root / "crates/binja-xtensa/src/model.rs"
if "--check" in sys.argv:
    sys.exit(0 if dest.read_text() == text else "model.rs is stale; run harness/gen_model_rs.py")
dest.write_text(text)
