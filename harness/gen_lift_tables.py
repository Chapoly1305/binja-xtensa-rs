#!/usr/bin/env python3
"""Generate crates/binja-xtensa/src/lift/tables.rs from the reference plugin.

* The set of mnemonics that have a `_lift_*` handler in `lifter.py` (module
  globals; a name assigned twice keeps its last value, which does not change
  membership).
* `ar_operands.AR_FIELDS`, `IMPLICIT_AR` and `SPECIAL_WINDOW_RULES` (the
  WindowCheck operand metadata), evaluated by importing the pure-Python module.

Usage: gen_lift_tables.py --plugin-dir PATH/binja_xtensa
"""
import argparse
import importlib.util
import re
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--plugin-dir", required=True)
a = ap.parse_args()
plugin = Path(a.plugin_dir)

import sys, types


class _Dummy:
    def __init__(self, *a, **k):
        pass

    def __call__(self, *a, **k):
        return _Dummy()

    def __getattr__(self, name):
        return _Dummy()


def _stub(name):
    m = types.ModuleType(name)
    m.__getattr__ = lambda attr: _Dummy
    return m


for _n in ("binaryninja", "binaryninja.settings", "binaryninja.enums"):
    sys.modules[_n] = _stub(_n)
_pkg = types.ModuleType("xtensa_ref")
_pkg.__path__ = [str(plugin)]  # import submodules without running __init__.py
sys.modules["xtensa_ref"] = _pkg
_lifter = importlib.import_module("xtensa_ref.lifter")
handlers = sorted(k[len("_lift_"):] for k in vars(_lifter) if k.startswith("_lift_"))
spec = importlib.util.spec_from_file_location("ar_operands", plugin / "ar_operands.py")
ar = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ar)

root = Path(__file__).resolve().parents[1]
out = ["// @generated by harness/gen_lift_tables.py from the reference plugin. Do not edit.", ""]
out.append("/// Names `X` with a module-level `_lift_X` in the reference `lifter.py`")
out.append("/// (mnemonic with '.' replaced by '_'), including helpers such as `cond`.")
out.append(f"pub const LIFT_HANDLER_NAMES: [&str; {len(handlers)}] = [")
out += [f'    "{h}",' for h in handlers]
out.append("];")
out.append("")
out.append("/// `ar_operands.AR_FIELDS`: AR operand fields per mnemonic (with '_').")
out.append("pub fn ar_fields(name: &str) -> Option<&'static str> {")
out.append("    Some(match name {")
for k in sorted(ar.AR_FIELDS):
    out.append(f'        "{k}" => "{ar.AR_FIELDS[k]}",')
out.append("        _ => return None,")
out.append("    })")
out.append("}")
out.append("")
out.append("/// `ar_operands.IMPLICIT_AR`.")
out.append("pub fn implicit_ar(name: &str) -> &'static [i64] {")
out.append("    match name {")
for k in sorted(ar.IMPLICIT_AR):
    out.append(f'        "{k}" => &[{", ".join(map(str, ar.IMPLICIT_AR[k]))}],')
out.append("        _ => &[],")
out.append("    }")
out.append("}")
out.append("")
out.append("/// `ar_operands.SPECIAL_WINDOW_RULES`.")
out.append(f"pub const SPECIAL_WINDOW_RULES: [&str; {len(ar.SPECIAL_WINDOW_RULES)}] = [" +
           ", ".join(f'"{s}"' for s in sorted(ar.SPECIAL_WINDOW_RULES)) + "];")
(root / "crates/binja-xtensa/src/lift/tables.rs").write_text("\n".join(out) + "\n")
print(len(handlers), "handlers;", len(ar.AR_FIELDS), "AR_FIELDS entries")
